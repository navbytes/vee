import Foundation
import FluidProtocol

/// Compiles a single-file Swift plugin into a helper executable.
///
/// Each plugin gets a small generated SwiftPM package in the build cache that
/// depends on FluidKit by path, keyed by a hash of the source, so an unchanged
/// plugin is never rebuilt. A failed build returns the compiler's diagnostics,
/// mapped back to the plugin's own file — the loop an AI author needs: write,
/// build, read the errors, fix.
///
/// ponytail: every plugin compiles its own copy of FluidKit the first time,
/// which costs seconds per plugin. A shared prebuilt FluidKit module is phase
/// 1 work; until then the cache makes it a one-off per plugin version.
public struct PluginBuilder: Sendable {
    public struct Output: Sendable {
        public var binary: URL
        public var cached: Bool
    }

    public struct Failure: Error, CustomStringConvertible, Sendable {
        public var diagnostics: [BuildDiagnostic]
        public var log: String

        public var description: String {
            diagnostics.isEmpty ? log : diagnostics.map(\.description).joined(separator: "\n")
        }
    }

    /// The Fluid package (the directory holding Package.swift with FluidKit).
    public var fluidPackage: URL
    public var cacheRoot: URL
    public var configuration: String

    public init(fluidPackage: URL, cacheRoot: URL, configuration: String = "release") {
        self.fluidPackage = fluidPackage
        self.cacheRoot = cacheRoot
        self.configuration = configuration
    }

    public func build(source: URL) throws -> Output {
        let code = try Data(contentsOf: source)
        let name = Self.sanitizedName(source.deletingPathExtension().lastPathComponent)
        let key = Self.cacheKey(code + Data("\(configuration)|\(fluidPackage.path)".utf8))
        let packageDir = cacheRoot.appendingPathComponent("\(name)-\(key)", isDirectory: true)
        let binary = packageDir.appendingPathComponent(".build/\(configuration)/Plugin")

        if FileManager.default.isExecutableFile(atPath: binary.path) {
            return Output(binary: binary, cached: true)
        }

        let sourcesDir = packageDir.appendingPathComponent("Sources/Plugin", isDirectory: true)
        try FileManager.default.createDirectory(at: sourcesDir, withIntermediateDirectories: true)
        try Self.manifest(fluidPackage: fluidPackage).write(to: packageDir.appendingPathComponent("Package.swift"), atomically: true, encoding: .utf8)
        let copied = sourcesDir.appendingPathComponent("Plugin.swift")
        try code.write(to: copied)

        let (status, log) = try Self.run(["swift", "build", "-c", configuration, "--package-path", packageDir.path, "--product", "Plugin"])
        guard status == 0, FileManager.default.isExecutableFile(atPath: binary.path) else {
            let diagnostics = Self.parseDiagnostics(log).map { diagnostic in
                var mapped = diagnostic
                if diagnostic.file.hasSuffix("Sources/Plugin/Plugin.swift") { mapped.file = source.path }
                return mapped
            }
            throw Failure(diagnostics: diagnostics, log: log)
        }
        return Output(binary: binary, cached: false)
    }

    static func manifest(fluidPackage: URL) -> String {
        let path = fluidPackage.path.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
        return """
        // swift-tools-version: 6.2
        // Generated by Fluid. Edit the plugin's own .swift file, not this one.
        import PackageDescription

        let package = Package(
            name: "Plugin",
            platforms: [.macOS("26.0")],
            dependencies: [.package(path: "\(path)")],
            targets: [
                .executableTarget(name: "Plugin", dependencies: [.product(name: "FluidKit", package: "Fluid")], path: "Sources/Plugin"),
            ]
        )

        """
    }

    /// Compiler output lines of the form `file:line:col: error: message`.
    public static func parseDiagnostics(_ log: String) -> [BuildDiagnostic] {
        var seen = Set<String>()
        var result: [BuildDiagnostic] = []
        for line in log.split(whereSeparator: \.isNewline) {
            for severity in BuildDiagnostic.Severity.allCases {
                let marker = ": \(severity.rawValue): "
                guard let range = line.range(of: marker) else { continue }
                let location = line[..<range.lowerBound].split(separator: ":")
                guard location.count >= 3, let lineNumber = Int(location[location.count - 2]), let column = Int(location[location.count - 1]) else { continue }
                let file = location.dropLast(2).joined(separator: ":")
                let diagnostic = BuildDiagnostic(file: file, line: lineNumber, column: column, severity: severity, message: String(line[range.upperBound...]))
                if seen.insert(diagnostic.description).inserted { result.append(diagnostic) }
            }
        }
        return result
    }

    /// FNV-1a, 64-bit: a cache key, not a security boundary.
    static func cacheKey(_ data: Data) -> String {
        var hash: UInt64 = 0xcbf2_9ce4_8422_2325
        for byte in data {
            hash ^= UInt64(byte)
            hash = hash &* 0x0000_0100_0000_01b3
        }
        return String(hash, radix: 16)
    }

    static func sanitizedName(_ name: String) -> String {
        let allowed = name.unicodeScalars.map { CharacterSet.alphanumerics.contains($0) || $0 == "-" ? Character($0) : "-" }
        let result = String(allowed)
        return result.isEmpty ? "plugin" : result
    }

    static func run(_ arguments: [String]) throws -> (Int32, String) {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/env")
        process.arguments = arguments
        let output = Pipe()
        process.standardOutput = output
        process.standardError = output
        process.standardInput = FileHandle.nullDevice
        try process.run()
        let data = output.fileHandleForReading.readDataToEndOfFile()
        process.waitUntilExit()
        return (process.terminationStatus, String(decoding: data, as: UTF8.self))
    }

    #if os(macOS)
    /// Signs the helper ad hoc with entitlements generated from its manifest,
    /// so the App Sandbox applies when it launches.
    ///
    /// ponytail: unverified whether an ad-hoc-signed bare executable gets the
    /// full sandbox when launched by the host; that is the phase 0 Mac spike.
    /// The app only calls this when `FLUID_SANDBOX=1`.
    public func sign(binary: URL, manifest: Manifest) throws {
        let entitlementsFile = binary.deletingLastPathComponent().appendingPathComponent("Plugin.entitlements")
        try SandboxEntitlements.propertyList(for: manifest).write(to: entitlementsFile)
        let (status, log) = try Self.run(["codesign", "--force", "--sign", "-", "--identifier", manifest.id, "--entitlements", entitlementsFile.path, binary.path])
        if status != 0 { throw Failure(diagnostics: [], log: log) }
    }
    #endif
}

public struct BuildDiagnostic: Equatable, Sendable, CustomStringConvertible {
    public enum Severity: String, Sendable, CaseIterable {
        case error, warning
    }

    public var file: String
    public var line: Int
    public var column: Int
    public var severity: Severity
    public var message: String

    public var description: String { "\(file):\(line):\(column): \(severity.rawValue): \(message)" }
}
